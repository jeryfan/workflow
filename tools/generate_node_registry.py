#!/usr/bin/env python3
"""Generate the frontend and backend registries from contracts/nodes.json."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import sys
import tempfile
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[1]
PYTHON_REGISTRY = Path("api/src/api/services/node_registry.py")
TYPESCRIPT_EXCLUSIONS = Path("web-legacy/standalone/node-exclusions.generated.ts")
GENERATED_HEADER = "Generated by tools/generate_node_registry.py. Do not edit."


class RegistryError(Exception):
    pass


@dataclass(frozen=True, slots=True)
class NodeSpec:
    type: str
    frontend_directory: str
    execution_module: str | None
    execution_name: str | None
    show_in_catalog: bool
    default_config: dict[str, Any]
    support: str
    exclusion_reason: str | None

    @property
    def executable(self) -> bool:
        return self.support in {"ready", "internal"} and self.execution_module is not None


def parse_execution_class(node_type: str, value: object) -> tuple[str | None, str | None]:
    if value is None:
        return None, None
    if not isinstance(value, str) or "." not in value:
        raise RegistryError(
            f"Node {node_type} has an unresolvable execution_class: {value!r}"
        )
    module, name = value.rsplit(".", 1)
    if not all(part.isidentifier() for part in module.split(".")) or not name.isidentifier():
        raise RegistryError(
            f"Node {node_type} has an unresolvable execution_class: {value!r}"
        )
    return module, name


def load_nodes(contract_path: Path) -> tuple[NodeSpec, ...]:
    if not contract_path.is_file():
        raise RegistryError(f"Node contract does not exist: {contract_path}")
    try:
        contract = json.loads(contract_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise RegistryError(f"Cannot read node contract {contract_path}: {error}") from error
    if not isinstance(contract, dict) or not isinstance(contract.get("nodes"), list):
        raise RegistryError(f"Node contract must contain a nodes array: {contract_path}")

    nodes = []
    seen_types = set()
    seen_directories = set()
    for raw in contract["nodes"]:
        if not isinstance(raw, dict):
            raise RegistryError("Every node contract entry must be an object")
        try:
            node_type = raw["type"]
            frontend_directory = raw["frontend_directory"]
            default_config = raw["default_config"]
            show_in_catalog = raw["show_in_catalog"]
            support = raw["support"]
            exclusion_reason = raw["exclusion_reason"]
        except KeyError as error:
            raise RegistryError(f"Node contract entry is missing {error}") from error
        if not isinstance(node_type, str) or not node_type:
            raise RegistryError("Every node type must be a non-empty string")
        if node_type in seen_types:
            raise RegistryError(f"Duplicate node type: {node_type}")
        if (
            not isinstance(frontend_directory, str)
            or not frontend_directory
            or Path(frontend_directory).name != frontend_directory
            or frontend_directory in {".", ".."}
        ):
            raise RegistryError(f"Invalid frontend_directory for node {node_type}")
        if frontend_directory in seen_directories:
            raise RegistryError(f"Duplicate frontend_directory: {frontend_directory}")
        if not isinstance(default_config, dict):
            raise RegistryError(f"default_config must be an object for node {node_type}")
        if not isinstance(show_in_catalog, bool):
            raise RegistryError(f"show_in_catalog must be boolean for node {node_type}")
        if support not in {"ready", "pending", "internal", "excluded"}:
            raise RegistryError(f"Invalid support state for node {node_type}: {support}")
        if support == "excluded":
            if raw.get("execution_class") is not None:
                raise RegistryError(f"Excluded node {node_type} cannot have an execution_class")
            if show_in_catalog:
                raise RegistryError(f"Excluded node {node_type} cannot appear in the catalog")
            if exclusion_reason not in {"knowledge-base", "plugins", "tools", "agent"}:
                raise RegistryError(f"Excluded node {node_type} needs a valid exclusion_reason")
        elif exclusion_reason is not None:
            raise RegistryError(f"Node {node_type} has an exclusion_reason without excluded support")
        if support in {"ready", "pending"} and not show_in_catalog:
            raise RegistryError(f"Executable node {node_type} must appear in the catalog")
        module, name = parse_execution_class(node_type, raw.get("execution_class"))
        if support == "ready" and module is None:
            raise RegistryError(f"Ready node {node_type} needs an execution_class")
        node = NodeSpec(
            type=node_type,
            frontend_directory=frontend_directory,
            execution_module=module,
            execution_name=name,
            show_in_catalog=show_in_catalog,
            default_config=default_config,
            support=support,
            exclusion_reason=exclusion_reason,
        )
        seen_types.add(node_type)
        seen_directories.add(frontend_directory)
        nodes.append(node)
    return tuple(nodes)


def render_python(nodes: tuple[NodeSpec, ...]) -> bytes:
    executable = [node for node in nodes if node.executable]
    imports = [
        f"from {node.execution_module} import {node.execution_name}"
        for node in sorted(executable, key=lambda node: node.execution_module or "")
    ]
    builders = [
        f'    "{node.type}": {node.execution_name},'
        for node in executable
    ]
    content = "\n".join(
        [
            f"# {GENERATED_HEADER}",
            *imports,
            "",
            "NODE_BUILDERS = {",
            *builders,
            "}",
            "",
            '__all__ = ["NODE_BUILDERS"]',
            "",
        ]
    )
    return content.encode("utf-8")


def render_typescript(nodes: tuple[NodeSpec, ...]) -> bytes:
    supported = sorted(node.type for node in nodes if node.support in {"ready", "internal"})
    catalog = sorted(node.type for node in nodes if node.support == "ready" and node.show_in_catalog)
    panels = sorted(
        {
            panel
            for node in nodes
            if node.support == "excluded"
            for panel in {
                "knowledge-base": ("sources",),
                "tools": ("tools",),
            }.get(node.exclusion_reason or "", ())
            if panel
        }
    )
    content = "\n".join(
        [
            f"// {GENERATED_HEADER}",
            "const supportedNodeTypes = new Set<string>([",
            *(f"  {json.dumps(node_type, ensure_ascii=False)}," for node_type in supported),
            "])",
            "const catalogNodeTypes = new Set<string>([",
            *(f"  {json.dumps(node_type, ensure_ascii=False)}," for node_type in catalog),
            "])",
            "const excludedSelectorPanels = new Set<string>([",
            *(f"  {json.dumps(panel, ensure_ascii=False)}," for panel in panels),
            "])",
            "",
            "export const isExcludedNodeType = (type: string) => !supportedNodeTypes.has(type)",
            "",
            "export const isExcludedCatalogNodeType = (type: string) => !catalogNodeTypes.has(type)",
            "",
            "export const isExcludedSelectorPanel = (panel: string) =>",
            "  excludedSelectorPanels.has(panel)",
            "",
        ]
    )
    return content.encode("utf-8")


def render_registries(contract_path: Path) -> dict[str, bytes]:
    nodes = load_nodes(contract_path)
    return {
        PYTHON_REGISTRY.as_posix(): render_python(nodes),
        TYPESCRIPT_EXCLUSIONS.as_posix(): render_typescript(nodes),
    }


def write_registries(project_root: Path, files: dict[str, bytes]) -> None:
    for relative, content in sorted(files.items()):
        destination = project_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.is_file() or destination.read_bytes() != content:
            destination.write_bytes(content)


def compare_registries(project_root: Path, files: dict[str, bytes]) -> list[str]:
    with tempfile.TemporaryDirectory(prefix="node-registry-check-") as temporary:
        staged = Path(temporary)
        differences = []
        for relative, content in sorted(files.items()):
            expected = staged / relative
            expected.parent.mkdir(parents=True, exist_ok=True)
            expected.write_bytes(content)
            actual = project_root / relative
            if not actual.is_file() or actual.read_bytes() != expected.read_bytes():
                differences.append(relative)
        return differences


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-root",
        "--target-root",
        dest="output_root",
        type=Path,
        default=PROJECT_ROOT,
    )
    parser.add_argument("--contract", type=Path)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    project_root = args.output_root.expanduser().resolve()
    contract = (
        args.contract.expanduser().resolve()
        if args.contract
        else project_root / "contracts" / "nodes.json"
    )
    try:
        files = render_registries(contract)
        if args.check:
            differences = compare_registries(project_root, files)
            if differences:
                raise RegistryError(
                    "Stale generated registries: " + ", ".join(differences)
                )
        else:
            write_registries(project_root, files)
        print(json.dumps({"files": sorted(files)}, indent=2))
        return 0
    except (RegistryError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
